from PyQt6.QtWidgets import (
    QWidget, QVBoxLayout, QHBoxLayout, QLabel, QLineEdit, QComboBox,
    QDoubleSpinBox, QCheckBox, QGroupBox,
)
from ui.tab_constants import (
    _CMAP_LIST,
)


class ChartOptionGroupsMixin:
    def _build_chart_option_groups(self, layout):
        def _row(*widgets):
            h = QHBoxLayout()
            for w in widgets: h.addWidget(w)
            return h

        # ── Bar (chart-mode options only) ─────────────────────────────────────
        self.bar_group = QGroupBox('Bar Options')
